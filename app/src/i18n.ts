export const t = STRINGS[locale];
export const fmt = (s: string, n: string | number) => s.replace("{n}", String(n));

// 나라 이름. Hermes에 Intl.DisplayNames가 없을 수 있어 실패하면 코드 그대로
let names: Intl.DisplayNames | null = null;
try {
  names = new Intl.DisplayNames([locale], { type: "region" });
} catch {}
const flag = (geo: string) => String.fromCodePoint(...[...geo].map((c) => 0x1f1a5 + c.charCodeAt(0)));
export const countryName = (geo: string) => {
  let name = geo;
  try {
    name = names?.of(geo) ?? geo;
  } catch {}
  return `${flag(geo)} ${name}`;
};

export function ago(date: number) {
  const min = Math.max(1, Math.round((Date.now() - date) / 60000));
  return min < 60 ? fmt(t.minAgo, min) : fmt(t.hourAgo, Math.round(min / 60));
}
